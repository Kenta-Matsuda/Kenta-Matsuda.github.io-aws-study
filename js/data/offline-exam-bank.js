/**
 * 文字列を決定的な整数シードへ変換する（FNV-1a）。daily-challenge.js と同じ方式。
 * @param {string} str
 * @returns {number} 32bit 符号なし整数
 */
function stringToSeed(str) {
  let h = 2166136261 >>> 0; // FNV-1a offset basis
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/**
 * mulberry32: 小さく決定的な擬似乱数生成器。daily-challenge.js と同じ実装。
 * @param {number} seed
 * @returns {() => number} 0以上1未満の擬似乱数を返す関数
 */
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * プールの問題を指定 locale のレンダラー形状へ正規化する。
 * en フィールドが欠落している場合は ja フィールドにフォールバックする。
 * 出典 URL は解説末尾に追記して、buildMockQuizSystemPrompt の出典可視化と整合させる。
 * @param {object} q
 * @param {'ja'|'en'} locale
 * @returns {{ question: string, choices: string[], correctIndex: number, explanation: string }}
 */
function localizeQuestion(q, locale) {
  const useEn = locale === 'en';
  const baseExplanation = (useEn && q.explanationEn) ? q.explanationEn : q.explanation;
  const ref = q.reference ? `\n\n${useEn ? 'Reference' : '出典'}: ${q.reference}` : '';
  return {
    question: (useEn && q.questionEn) ? q.questionEn : q.question,
    choices: (useEn && Array.isArray(q.choicesEn)) ? q.choicesEn.slice() : q.choices.slice(),
    correctIndex: q.correctIndex,
    explanation: `${baseExplanation}${ref}`,
  };
}

/**
 * 指定した試験レベルに対応する静的問題プールを返す。
 * @param {string} level
 * @returns {Array<object>}
 */
export function getPoolForLevel(level) {
  return LEVEL_POOLS[level] || ASSOCIATE_QUESTIONS;
}

/**
 * APIキー不要の本番形式模擬試験用に、静的バンクから決定的に問題を返す。
 *
 * examId から試験レベルを解決し（js/quiz.js の getExamLevel を再利用）、そのレベルの
 * 共有プールから決定的にシャッフルした問題を count 件返します。count はプールサイズで
 * クランプされます。AI プロバイダーや API キーは一切不要な、純粋・同期・副作用なしの関数です。
 *
 * @param {string} examId 対象の試験ID（例: 'clf-c02', 'saa-c03'）
 * @param {number} [count=65] 返す問題数（プールサイズ上限でクランプ）
 * @param {{ locale?: 'ja'|'en', seed?: string|number }} [opts]
 * @returns {Array<{ question: string, choices: string[], correctIndex: number, explanation: string }>}
 */
export function getOfflineExamQuestions(examId, count = 65, opts = {}) {
  const locale = opts.locale === 'en' ? 'en' : 'ja';
  const level = getExamLevel(examId);
  const pool = getPoolForLevel(level);
  const total = pool.length;
  const n = Math.max(0, Math.min(Number(count) || 0, total));
  if (n === 0) return [];

  // シードは、明示指定があればそれを、なければ examId + level を用いて決定的にする。
  // 同一 examId では毎回同じ順序になり、リロードや再挑戦でも安定した本番形式セットを得られる。
  const seedSource = opts.seed != null ? String(opts.seed) : `${examId || ''}::${level}`;
  const rand = mulberry32(stringToSeed(seedSource));

  // インデックス配列を決定的にシャッフル(Fisher-Yates)し、先頭 n 件を選ぶ。
  const indices = pool.map((_, i) => i);
  for (let i = indices.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    const tmp = indices[i];
    indices[i] = indices[j];
    indices[j] = tmp;
  }

  return indices.slice(0, n).map((idx) => localizeQuestion(pool[idx], locale));
}

/**
 * 指定した試験でオフライン模擬試験に利用できる問題数（プールサイズ）を返す。
 * UI ラベルで実際の出題数を正直に表示するために使う。
 * @param {string} examId
 * @returns {number}
 */
export function getOfflineExamPoolSize(examId) {
  return getPoolForLevel(getExamLevel(examId)).length;
}
