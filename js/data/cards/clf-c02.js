/**
 * CLF-C02 concept cards and framework maps (issue #225, design §3 / §4.2 / §4.3).
 *
 * Profile: foundational. Most units are `concept` cards (one card = one unit):
 * definitions, service identification and the shared responsibility model.
 * Three parts of Domain 1 are framework-shaped and are kept as `framework`
 * maps instead, so their structure comes from the source and not from the
 * model:
 *   - 1.1 / 1.4  "Six advantages of cloud computing" (Overview of Amazon Web Services)
 *   - 1.2        AWS Well-Architected Framework: general and per-pillar design principles
 *   - 1.3        AWS CAF: business outcomes, transformation domains, six perspectives, four phases
 *
 * Sources: AWS official documentation overview pages ("What is …?"), the
 * Overview of Amazon Web Services whitepaper, the Well-Architected Framework,
 * An Overview of the AWS Cloud Adoption Framework, AWS Prescriptive Guidance
 * (7 Rs), the disaster recovery whitepaper, and the AWS Support / Billing
 * pages. Every page was fetched and read on 2026-10-19 and definitions follow
 * its wording; where a confusable's "why" goes beyond the cited page it only
 * restates the other service's own overview page, which is also cited by its
 * own card here. `How AWS Pricing Works` is marked "historical reference only"
 * on docs.aws.amazon.com, so the cards that use it carry `archived: true`.
 *
 * Things that changed recently and are reflected here (check on review):
 *   - Support plans: Basic / Business Support+ / Enterprise Support / Unified
 *     Operations. Developer, Business and Enterprise On-Ramp end 2027-01-01.
 *   - Renames: AppStream 2.0 → WorkSpaces Applications, Application Migration
 *     Service → AWS Transform MGN, QuickSight → Quick Sight (part of Amazon
 *     Quick), Security Hub → Security Hub CSPM, Amazon Connect → Connect Customer.
 *
 * `stage` in the framework maps is editorial where the source has no stage
 * (Well-Architected principles are all "設計原則"; CAF perspectives are
 * "横断" because the paper does not tie them to one phase).
 *
 * Mined 2026-10-19. Human review required before relying on these for
 * published questions.
 */

const V = '2026-10-19';
const D = 'https://docs.aws.amazon.com';

function src(title, url, extra = {}) {
  return { title, url, verifiedAt: V, ...extra };
}

function c(id, term, service, definition, confusables, tasks, source) {
  return {
    id: `clf-concept-${id}`,
    kind: 'concept',
    term,
    service,
    definition,
    confusables: confusables.map(([option, why]) => ({ option, why })),
    tasks,
    level: 'foundational',
    source,
  };
}

function cell(id, perspective, stage, capability, summary, misconceptions, tasks) {
  return { id, perspective, stage, capability, summary, misconceptions, tasks };
}

